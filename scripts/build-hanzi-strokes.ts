/**
 * Vendor the Han stroke dataset the CJK spelling coda draws from.
 *
 * The coda animates each Chinese answer stroke-by-stroke (笔顺) with Hanzi Writer,
 * which needs per-character outline paths + medians that Unicode alone cannot give.
 * Rather than fetch them from a third-party CDN, this script scans every deck the feed
 * can serve, collects the Han characters it actually contains, and copies just those
 * characters' stroke data out of `hanzi-writer-data` into ONE STATIC FILE PER CHARACTER
 * under public/. The host serves them as plain cached assets: no server work per reader,
 * and a reader downloads only the characters of the cards they actually meet (~1.2 KB
 * each compressed), so the deck can grow to thousands of characters without a heavy
 * up-front download.
 *
 * The folder is named after the hanzi-writer-data version, the only thing that can change
 * a character's file, so adding characters never invalidates what readers already cached.
 * Files are named by hex code point to keep URLs ASCII.
 *
 * Re-run whenever a CJK deck is added or edited:
 *   npx tsx scripts/build-hanzi-strokes.ts
 *
 * Output: public/hanzi/<version>/<codepoint>.json  ({ strokes, medians, radStrokes? })
 *         src/features/vocabulary/data/hanzi-strokes-version.ts  (the folder name)
 * Attribution: stroke outlines derive from Make Me a Hanzi (Arphic Public License) via
 * the hanzi-writer-data package; see docs/cjk-korean-hint-equivalents.md.
 * Depends on: hanzi-writer-data, node:fs, node:path, node:url, node:crypto
 */
import { createRequire } from "node:module";
import { randomUUID } from "node:crypto";
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const dataDir = resolve(here, "../src/features/vocabulary/data");
const publicRoot = resolve(here, "../public/hanzi");
const versionPath = join(dataDir, "hanzi-strokes-version.ts");
const version = (require("hanzi-writer-data/package.json") as { version: string }).version;

/** A single Han character; Hangul and kana are out of scope for this coda. */
const HAN = /\p{Script=Han}/u;

type StrokeEntry = { strokes: string[]; medians: number[][][]; radStrokes?: number[] };

/** Every .json deck the feed can serve: base catalog, provider packs and each locale folder. */
function collectDecks(dir: string): string[] {
  const found: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const info = statSync(full);
    if (info.isDirectory()) found.push(...collectDecks(full));
    else if (name.endsWith(".json")) found.push(full);
  }
  return found;
}

const chars = new Set<string>();
for (const file of collectDecks(dataDir)) {
  const deck = JSON.parse(readFileSync(file, "utf8")) as { words?: { word?: string }[] };
  for (const entry of deck.words ?? []) {
    for (const ch of Array.from(entry.word ?? "")) if (HAN.test(ch)) chars.add(ch);
  }
}

const out: Record<string, StrokeEntry> = {};
const missing: string[] = [];
for (const ch of [...chars].sort()) {
  let data: StrokeEntry | undefined;
  try {
    data = require(`hanzi-writer-data/${ch}.json`) as StrokeEntry;
  } catch {
    data = undefined;
  }
  if (!data?.strokes?.length) {
    missing.push(ch);
    continue;
  }
  out[ch] = data.radStrokes
    ? { strokes: data.strokes, medians: data.medians, radStrokes: data.radStrokes }
    : { strokes: data.strokes, medians: data.medians };
}

if (missing.length) {
  console.error(
    `Missing stroke data for ${missing.length} character(s): ${missing.join(" ")}. ` +
      `Install/refresh hanzi-writer-data or drop them from the deck.`,
  );
  process.exitCode = 1;
}

// Build the whole folder beside the live one, then swap it in, so the previous dataset
// survives if anything above threw. Older version folders go: nothing references them.
const staging = join(publicRoot, `.${randomUUID()}.tmp`);
mkdirSync(staging, { recursive: true });
for (const [ch, entry] of Object.entries(out)) {
  writeFileSync(join(staging, `${ch.codePointAt(0)!.toString(16)}.json`), JSON.stringify(entry));
}
for (const name of readdirSync(publicRoot)) {
  if (join(publicRoot, name) !== staging) rmSync(join(publicRoot, name), { recursive: true });
}
renameSync(staging, join(publicRoot, version));
writeFileSync(
  versionPath,
  `/** Generated by scripts/build-hanzi-strokes.ts: the public/hanzi/ folder holding the stroke files. */\n` +
    `export const HANZI_STROKES_VERSION = ${JSON.stringify(version)};\n`,
);
console.log(
  `Wrote ${Object.keys(out).length} Han character(s) → public/hanzi/${version}/` +
    (missing.length ? ` (${missing.length} missing, see above)` : ""),
);
